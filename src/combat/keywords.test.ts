/**
 * Покрытие канонических кейвордов: каждый прочитан движком.
 *
 * `parseKeyword` на незнакомом тексте НЕ падает: он склеивает его в имя вида
 * 'blah-blah' и отдаёт дальше. Такой кейворд молча доезжает до данных и
 * ничего не делает — ни одно правило в `rules.ts`/`simulate.ts` его не читает,
 * а ошибки не возникает (ровно так потерялся RENDAX у Shield-Captain: 'Active'
 * превратился в 'active', и полсотни юнитов получили несуществующий эффект).
 *
 * Проверять «строка разобралась» поэтому недостаточно. Этот тест идёт с другой
 * стороны: не по данным BSData, а по ПРОД-КОДУ. Каждое имя из
 * `CANONICAL_KEYWORD_NAMES` обязано встретиться в коде литералом `'имя'` —
 * там, где движок решает, что кейворд значит. Если имя есть в списке
 * канонических, но не читается нигде, оно либо мёртвое, либо читается по
 * сырой строке мимо разбора, и оба случая надо видеть.
 *
 * Обходятся `src`, `scripts` и `web/src`: кейворд может читаться и в сборщике,
 * и в скриптах отчётов. Минус сам `keywords.ts` (там само объявление списка —
 * иначе проверка всегда «зелёная») и `*.test.ts` (в тестах литералы нужны для
 * утверждений, а не для разбора).
 */

import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { CANONICAL_KEYWORD_NAMES } from './keywords.ts';

/**
 * Кейворды, которые разбираются канонически, но НИГДЕ не читаются движком.
 *
 * Список явный и с причиной по каждому имени: пустой список означал бы, что
 * движок знает все канонические имена, а это неправда — часть имён нужна для
 * нормализации сырых строк, а не для эффекта.
 */
const UNSUPPORTED_KEYWORDS: ReadonlyArray<[name: string, reason: string]> = [
  [
    'indirect',
    'INDIRECT FIRE — это про наведение по площади (STR 25 → только по врагу в укрытии на дистанции 10" и ближе, если цель не укрыта). Оно меняет ПРАВИЛА наведения, а не характеристики выстрела, и в расчёте урона ни одной строки не занимает: поданное в BSData оружие с этим кейвордом считается тем же, что без него. Считать это отдельной осью нужно вместе с моделью наведения — она в проекте есть только в заготовке `standardRules`.',
  ],
  [
    'hazardous',
    'HAZARDOUS (аналог DANGER ZONE в 10e) — «один бросок урона без таблицы» на каждую модель в зоне. Зона опасности не смоделирована: модель боя не различает позиции и не знает, кто в неё попал, поэтому даже полный разбор кейворда не дал бы ни одной атаки. Флаг в utility не ставится намеренно — платить баллы за неработающий эффект хуже, чем не платить.',
  ],
];

/**
 * Одноразовые исследовательские скрипты: сырые сканеры по BSData.
 *
 * Исключены потому, что они не ЧИТАЮТ кейворды, а ищут их текстом в JSON
 * игры: там литералы — часть поискового запроса, а не решение движка. Если бы
 * они считались, проверка прошла бы для любого имени, которое хоть раз
 * упомянули в скрипте, — то есть не проверяла бы ничего. Боевой код при этом
 * лежит в `src`, а `scripts/build-tierlist.ts` и отчёты остаются в обходе.
 */
const RESEARCH_SCRIPTS = /-scan\.mjs$|^dump\.mjs$|^probe-.*\.mjs$|^kw-scan\.mjs$/;

const ROOTS = ['src', 'scripts', 'web/src'];

/** Все прод-файлы под указанными корнями: пути нормализованы в `/`. */
function productionFiles(): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
        continue;
      }
      if (!/\.(ts|mjs|js)$/.test(entry)) continue;
      // Минус само объявление списка: иначе имя всегда «найдено» самим собой.
      if (entry === 'keywords.ts') continue;
      // Минус тесты: литералы там нужны для утверждений, а не для разбора.
      if (entry.endsWith('.test.ts')) continue;
      if (RESEARCH_SCRIPTS.test(entry)) continue;
      out.push(relative(process.cwd(), full).split(sep).join('/'));
    }
  };
  for (const root of ROOTS) walk(root);
  return out;
}

describe('покрытие канонических кейвордов', () => {
  const files = productionFiles();
  // Один раз читаем все файлы: поштучный readFileSync на каждый кейворд означал
  // бы 22 полных обхода дерева вместо одного.
  const sources = files.map((file) => ({ file, text: readFileSync(file, 'utf8') }));
  const read = (name: string): string[] =>
    sources
      .filter(({ text }) => text.includes(`'${name}'`) || text.includes(`"${name}"`))
      .map(({ file }) => file);

  it('обход находит прод-код: список файлов не пуст и корни существуют', () => {
    // Без этого шага пустой ROOTS дал бы «зелёный» тест с нулём файлов: ни одно
    // утверждение ниже не проверялось бы, а падение выглядело бы как успех.
    for (const root of ROOTS) {
      expect(statSync(root).isDirectory(), `корень обхода ${root} должен существовать`).toBe(true);
    }
    expect(files.length, 'обход должен видеть прод-файлы').toBeGreaterThan(30);
    expect(files, 'исходник движка обязан попасть в обход').toContain('src/combat/rules.ts');
    expect(files, 'список канонических имён не должен попадать в обход').not.toContain(
      'src/combat/keywords.ts'
    );
  });

  it('каждый канонический кейворд читается прод-кодом или помечен как неподдерживаемый', () => {
    const unsupported = new Map(UNSUPPORTED_KEYWORDS);
    // Ключи списка не должны быть «мёртвыми» сами по себе: имя, которого больше
    // нет в CANONICAL_KEYWORD_NAMES, означало бы, что список кейвордов изменился,
    // а объяснение осталось от старой версии.
    const stale = [...unsupported.keys()].filter((name) => !CANONICAL_KEYWORD_NAMES.includes(name));
    expect(stale, `в UNSUPPORTED_KEYWORDS есть неизвестные имена: ${stale.join(', ')}`).toEqual([]);

    const missing = CANONICAL_KEYWORD_NAMES.filter(
      (name) => read(name).length === 0 && !unsupported.has(name)
    );
    expect(
      missing,
      `кейворды разбираются канонически, но их никто не читает. Либо движок потерял ` +
        `чтение (и эффект молча пропал из расчёта), либо имя нужно удалить из ` +
        `CANONICAL. Мёртвые: ${missing.join(', ')}`
    ).toEqual([]);
  });

  it('неподдерживаемые кейворды объяснены, а не просто перечислены', () => {
    // Причина обязательна: пустая строка прошла бы проверку выше и оставила бы
    // следующего читателя гадать, почему эффекта нет.
    for (const [name, reason] of UNSUPPORTED_KEYWORDS) {
      expect(reason.trim().length, `${name}: нужна причина, почему кейворд не читается`).toBeGreaterThan(40);
    }
  });

  it('механика [ONE SHOT] и [ASSAULT] читается в прод-коде, а не только в тестах', () => {
    // Отдельное утверждение вместо строчки в общем списке: эти два кейворда
    // добавлены последними, и именно они должны подтвердить, что правки не
    // молчаливые. Если завтра кто-то уберёт чтение из движка, падать будет
    // здесь, с понятным текстом, а не списком из трёх имён.
    expect(read('one-shot'), '[ONE SHOT] обязан читаться адаптером (флаг onceOnly)').toContain(
      'src/combat/adapter.ts'
    );
    expect(read('assault'), '[ASSAULT] обязан читаться разбором полезности').toContain(
      'src/tier/utility.ts'
    );
  });
});
