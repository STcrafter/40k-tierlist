/**
 * Тип юнита как данные, а не как ручной перечислитель.
 *
 * Раньше `ArchetypeId` был закрытым union из 13 значений, и типы задавались
 * вручную. Эта типизация оказалась кривой: корзина «infantry» объединяла и
 * обычную пехоту, и героев, и фланг-инфантрию, а «flyer/transport/vehicle»
 * различались там, где данные их не различают. Теперь набор типов выводится
 * из k-means (см. scripts/build-clusters.ts), поэтому идентификатор — строка.
 */

/** Идентификатор типа: приходит из сгенерированного кластера. */
export type ArchetypeId = string;

/**
 * Семантическая группа типа — для парадигм «против X».
 *
 * Парадигмы (infantry / armor) больше не перечисляют id вручную: они
 * фильтруют по группе, поэтому у каждого типа группа должна быть одна.
 */
export type ArchetypeGroup = 'infantry' | 'armor';

/** Описание типа: геометрия эталона цели плюс его происхождение в данных. */
export interface ClusterProfile {
  id: ArchetypeId;
  name: string;
  group: ArchetypeGroup;
  /** Кейворды, встречающиеся у большинства юнитов кластера. */
  keywords: string[];
  models: number;
  toughness: number;
  wounds: number;
  save: number | null;
  invuln: number | null;
  points: number;
  /** Сколько реальных юнитов попало в кластер (для отчётов). */
  sample: number;
}

/**
 * Группа кластера выводится из данных, а не задаётся списком: тип относится к
 * пехоте, если кейворд INFANTRY есть у большинства его юнитов.
 *
 * Так группа переживает смену K — при K=6 или K=8 разбиение меняется, и
 * жёстко прописанный массив групп разъехался бы с реальностью.
 */
export const INFANTRY_KEYWORD = 'INFANTRY';

