/**
 * Дэттачменты и правила фракций для клиента.
 *
 * В BSData дэттачментов нет: сборка `scripts/build-tierlist.ts` работает по
 * даташитам юнитов, а не по кодексам. Поэтому здесь — ЗАГОЛУШКИ: список
 * фракций, у которых дэттачменты заведены, с нейтральными именами и пустым
 * набором меток. Названия кодексные не ставились намеренно: переименование
 * одного файла дешевле, чем переименование в разметке и в тестах, когда
 * появится настоящий источник дэттачментов.
 *
 * ЧИСЛА НЕ МЕНЯЮТСЯ. Дэттачмент — правило построения армии, а не свойство
 * юнита: тот же юнит в двух дэттачментах один и тот же, и подставлять ему
 * разные метрики значило бы показать два разных тира одной строке. Сейчас
 * выбор дэттачмента ставит на строках только маркер — тем же способом, что и
 * Riled Up в main.ts. Считать бонус дэттачмента имеет смысл только когда в
 * сборке появится второй датасет (тот же юнит в базе «с дэттачментом»), и
 * тогда бонус посчитает сборка, а не браузер (см. web/src/model.ts: модель
 * данных намеренно не пересчитывает тиры на клиенте).
 */

/** Заготовка дэттачмента одной фракции. */
export interface DetachmentStub {
  /** Идентификатор для состояния клиента; совпадает с ключом записи. */
  id: string;
  /** Подпись в панели управления. */
  name: string;
  /**
   * Имена юнитов, которым дэттачмент ставит маркер в таблице.
   *
   * Сопоставление по имени юнита — то же, по которому отбираются пары
   * «отряд + лидер»: у BSData нет устойчивого идентификатора дэттачмента, а
   * переименование юнита в кодексе обязано ломать метку, а не молча
   * переносить её на другой юнит.
   */
  marks: string[];
}

/**
 * Дэттачменты по фракциям.
 *
 * Ключ — имя фракции из индекса (`IndexData.factions`), а не внутренний id:
 * фильтр по фракции на клиенте тоже работает по имени, и сводить два списка
 * к одному ключу дешевле, чем держать таблицу перевода.
 */
export const FACTION_DETACHMENTS: Record<string, DetachmentStub[]> = {
  // Заглушки: настоящие кодексные дэттачменты Орков в BSData отсутствуют.
  // Метки пустые, поэтому выбор дэттачмента пока ничего не подсвечивает —
  // блок нужен, чтобы место под них было видно и в разметке, и в тестах.
  Orks: [
    { id: 'Orks-1', name: 'Orks-1', marks: [] },
    { id: 'Orks-2', name: 'Orks-2', marks: [] },
  ],
};

/** Дэттачменты фракции; пустой список, если для неё их не завели. */
export function detachmentsOf(faction: string): DetachmentStub[] {
  return FACTION_DETACHMENTS[faction] ?? [];
}

/**
 * Имена юнитов, отмеченных выбранными дэттачментами.
 *
 * Считается на лету из небольшого набора заглушек: держать второй,
 * производный список означало бы завести ещё одно место, где можно забыть
 * синхронизировать состояние с тем, что показано в панели.
 */
export function marksOf(detachmentIds: readonly string[], faction: string): Set<string> {
  const marks = new Set<string>();
  for (const stub of detachmentsOf(faction)) {
    if (!detachmentIds.includes(stub.id)) continue;
    for (const name of stub.marks) marks.add(name);
  }
  return marks;
}
